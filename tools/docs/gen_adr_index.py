#!/usr/bin/env python3
"""The index of the architecture decision records, docs/adr/README.md.

    gen_adr_index.py            write docs/adr/README.md
    gen_adr_index.py --check    fail if it is out of date or an ADR is malformed (gate.sh, CI)

The index is built from each ADR's own lines, so it cannot say anything the
ADRs do not: the title (`# ADR NNNN: title`, the number matching the file
name), `- Status:` (which may wrap onto indented lines and must start with
proposed, accepted, rejected, deprecated or superseded) and `- Date:`.
An ADR that names another in a `- Supersedes:` line must be named back in
that ADR's status, so a superseded decision says so where it is read.
"""

import re
import sys
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
STATES = ("proposed", "accepted", "rejected", "deprecated", "superseded")
FILE = re.compile(r"^(\d{4})-[a-z0-9-]+\.md$")
TITLE = re.compile(r"^# ADR (\d{4}): (.+)$")
REF = re.compile(r"\[?ADR (\d{4})\]?(?:\([^)]*\))?")

HEADER = """\
# Architecture decision records

<!-- Generated by tools/docs/gen_adr_index.py from the ADRs themselves; do not edit by hand.
     After adding an ADR or changing a Status line, run the script; gate.sh and CI check it. -->

Each record states a decision that crosses subsystems, with its Context, Decision and
Consequences (Michael Nygard's format).

- A new ADR starts as **proposed**; only the maintainer accepts it.
- An accepted ADR is not rewritten. A change to its decision is a new ADR that supersedes or
  amends it, and the old one's Status line says which part was replaced and by what.
- The Status column below is each ADR's own Status line.

| ADR | Title | Status | Date |
|-----|-------|--------|------|
"""


@dataclass
class Adr:
    number: str
    path: Path
    title: str
    status: str
    date: str
    supersedes: str


def field(lines: list[str], name: str) -> str | None:
    """The text of a `- Name:` line and its indented continuation lines."""
    for i, line in enumerate(lines):
        if line.startswith(f"- {name}:"):
            parts = [line[len(name) + 3 :].strip()]
            for more in lines[i + 1 :]:
                if not more.startswith("  ") or not more.strip():
                    break
                parts.append(more.strip())
            return " ".join(parts)
    return None


def parse(path: Path, errors: list[str]) -> Adr | None:
    m = FILE.match(path.name)
    if not m:
        errors.append(f"{path.name}: file name is not NNNN-title.md")
        return None
    lines = path.read_text(encoding="utf-8").splitlines()
    t = TITLE.match(lines[0]) if lines else None
    if not t or t.group(1) != m.group(1):
        errors.append(f"{path.name}: first line is not '# ADR {m.group(1)}: <title>'")
        return None
    status, date = field(lines, "Status"), field(lines, "Date")
    if not status or status.split()[0].strip(";,.:()").lower() not in STATES:
        errors.append(f"{path.name}: Status must start with one of {', '.join(STATES)}")
        return None
    if not date:
        errors.append(f"{path.name}: no '- Date:' line")
        return None
    return Adr(
        m.group(1), path, t.group(2), status, date, field(lines, "Supersedes") or ""
    )


def links(text: str, known: dict[str, Adr]) -> str:
    def one(m: re.Match) -> str:
        a = known.get(m.group(1))
        return f"[ADR {m.group(1)}]({a.path.name})" if a else m.group(0)

    return REF.sub(one, text).replace("|", "\\|")


def render(adrs: list[Adr]) -> str:
    known = {a.number: a for a in adrs}
    rows = []
    for a in adrs:
        status = a.status
        if a.supersedes:
            status += f"; supersedes {a.supersedes}"
        rows.append(
            f"| [{a.number}]({a.path.name}) | {a.title.replace('|', chr(92) + '|')} "
            f"| {links(status, known)} | {a.date} |"
        )
    return HEADER + "\n".join(rows) + "\n"


def build(adr_dir: Path) -> tuple[str, list[str]]:
    errors: list[str] = []
    adrs = []
    for p in sorted(adr_dir.glob("*.md")):
        if p.name == "README.md":
            continue
        a = parse(p, errors)
        if a:
            adrs.append(a)
    known = {a.number: a for a in adrs}
    numbers = [int(a.number) for a in adrs]
    if numbers != list(range(1, len(numbers) + 1)):
        errors.append("ADR numbers are not 0001 upward without gaps")
    for a in adrs:
        for n in REF.findall(a.supersedes):
            other = known.get(n)
            if not other:
                errors.append(
                    f"{a.path.name}: supersedes ADR {n}, which does not exist"
                )
            elif f"ADR {a.number}" not in other.status:
                errors.append(
                    f"{other.path.name}: superseded by ADR {a.number}, but its Status does not say so"
                )
    return render(adrs), errors


def main(argv: list[str]) -> int:
    check = "--check" in argv
    root = Path(argv[argv.index("--root") + 1]) if "--root" in argv else REPO
    adr_dir = root / "docs" / "adr"
    text, errors = build(adr_dir)
    for e in errors:
        print(f"gen_adr_index: {e}", file=sys.stderr)
    if errors:
        return 1
    index = adr_dir / "README.md"
    if check:
        if not index.exists() or index.read_text(encoding="utf-8") != text:
            print(
                "gen_adr_index: docs/adr/README.md is out of date; run tools/docs/gen_adr_index.py",
                file=sys.stderr,
            )
            return 1
        return 0
    index.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
