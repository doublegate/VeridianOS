"""KDocTools 6.30: language customization files found, and relocatable.

1. kde-include-common.xsl loads a document's KDE language customization
   from xsl/<lang>.xml with the document's lang attribute as written:
   "pt-BR" asks for xsl/pt-BR.xml, but the file is xsl/pt_br.xml -- the
   form DocBook's own l10n code uses (lower case, '_' for '-'). Every
   Brazilian Portuguese handbook failed to load it ("I/O warning: failed
   to load .../pt-BR.xml") and went without it. The name is now
   normalized the same way.

2. all-l10n.xml (generated by docbookl10nhelper) names the DocBook XSL
   language files by absolute path. With RELOCATABLE_DOCBOOK_FILES the
   kde-include*.xsl files are rewritten at install time with paths
   relative to where they are installed; all-l10n.xml was installed as
   generated, so a cross build installed the build host's sysroot paths
   into the target's file. It now gets the same treatment: at install
   time its DocBook XSL directory becomes a path relative to the
   installed file.

Idempotent.

Usage: kdoctools_l10n.py <KDocTools source directory>
"""

import sys
from pathlib import Path

root = Path(sys.argv[1])


def replace_once(path, old, new):
    text = path.read_text()
    if new in text:
        return
    if text.count(old) != 1:
        sys.exit(f"{path}: expected one match, found {text.count(old)}")
    path.write_text(text.replace(old, new))


replace_once(
    root / "src/customization/kde-include-common.xsl.cmake",
    "select=\"document(concat('xsl/',/*/@lang,'.xml'))\"",
    "select=\"document(concat('xsl/',translate(/*/@lang,"
    "'ABCDEFGHIJKLMNOPQRSTUVWXYZ-','abcdefghijklmnopqrstuvwxyz_'),'.xml'))\"",
)

replace_once(
    root / "src/CMakeLists.txt",
    "# all-l10n.xml is generated by docbookl10nhelper\n"
    "install(FILES ${CMAKE_CURRENT_BINARY_DIR}/customization/xsl/all-l10n.xml\n"
    "    DESTINATION ${KDE_INSTALL_DATADIR_KF}/kdoctools/customization/xsl/ )\n",
    "# all-l10n.xml is generated by docbookl10nhelper\n"
    "if(NOT RELOCATABLE_DOCBOOK_FILES)\n"
    "    install(FILES ${CMAKE_CURRENT_BINARY_DIR}/customization/xsl/all-l10n.xml\n"
    "        DESTINATION ${KDE_INSTALL_DATADIR_KF}/kdoctools/customization/xsl/ )\n"
    "else()\n"
    "    # Its DocBook paths relative to where it is installed, as for the\n"
    "    # kde-include*.xsl files above.\n"
    "    install(CODE\n"
    '        "file(RELATIVE_PATH _l10n_docbook_dir ${CMAKE_SYSROOT}/\\${CMAKE_INSTALL_PREFIX}/'
    "${KDE_INSTALL_DATADIR_KF}/kdoctools/customization/xsl ${DOCBOOKXSL_DIR})\n"
    '        file(READ \\"${CMAKE_CURRENT_BINARY_DIR}/customization/xsl/all-l10n.xml\\" _l10n)\n'
    '        string(REPLACE \\"${DOCBOOKXSL_DIR}/\\" \\"\\${_l10n_docbook_dir}/\\" _l10n \\"\\${_l10n}\\")\n'
    '        file(WRITE \\"${CMAKE_CURRENT_BINARY_DIR}/customization/xsl/all-l10n.xml.install\\" \\"\\${_l10n}\\")")\n'
    "    install(FILES ${CMAKE_CURRENT_BINARY_DIR}/customization/xsl/all-l10n.xml.install\n"
    "        DESTINATION ${KDE_INSTALL_DATADIR_KF}/kdoctools/customization/xsl/ RENAME all-l10n.xml)\n"
    "endif()\n",
)
