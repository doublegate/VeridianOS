#!/usr/bin/env python3
"""The Linux kernel configuration VeridianOS reports (ADR 0023).

Turns abi/kconfig.map into the config file a Linux distribution installs
as /boot/config-<release>, which LTP's tst_kconfig and other programs read
to learn what the kernel was built with.

    gen_kconfig.py --check          check abi/kconfig.map (gate.sh, CI)
    gen_kconfig.py --print ARCH     write ARCH's config to stdout
    gen_kconfig.py ARCH ROOT        write it to ROOT/boot/config-<release>

The check fails when an option set to anything but n names a system call
that the kernel does not implement (missing, or a stub, as
syscall_coverage.py classifies them) or that Linux does not have on an
architecture the line applies to.
"""

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import syscall_coverage

REPO = Path(__file__).resolve().parents[2]
ARCHES = ("x86_64", "aarch64", "riscv64")
NAME = re.compile(r"CONFIG_[A-Z0-9_]+")


@dataclass
class Option:
    name: str
    value: str
    needs: list[str] = field(default_factory=list)
    arches: tuple[str, ...] = ARCHES
    line: int = 0


def parse(text: str) -> list[Option]:
    """The options of a kconfig.map text; ValueError names a bad line."""
    options, seen = [], set()
    for number, raw in enumerate(text.splitlines(), 1):
        fields = raw.split("#", 1)[0].split()
        if not fields:
            continue
        name, *rest = fields
        if not NAME.fullmatch(name) or not rest:
            raise ValueError(f"kconfig.map:{number}: expected CONFIG_<NAME> <value>")
        if name in seen:
            raise ValueError(f"kconfig.map:{number}: {name} appears twice")
        seen.add(name)
        option = Option(name, rest[0], line=number)
        for extra in rest[1:]:
            key, _, value = extra.partition("=")
            if key == "needs" and value:
                option.needs = value.split(",")
            elif key == "arch" and value:
                option.arches = tuple(value.split(","))
                unknown = set(option.arches) - set(ARCHES)
                if unknown:
                    raise ValueError(
                        f"kconfig.map:{number}: unknown arch {sorted(unknown)}"
                    )
            else:
                raise ValueError(f"kconfig.map:{number}: unexpected {extra!r}")
        options.append(option)
    return options


def problems(
    options: list[Option], implemented: set[str], linux: dict[str, set[str]]
) -> list[str]:
    """Why the options claim more than the kernel does, if they do.
    `linux` maps each architecture to the system calls Linux has on it."""
    found = []
    for o in options:
        if o.value == "n":
            continue
        for arch in o.arches:
            for call in o.needs:
                if call not in linux[arch]:
                    found.append(
                        f"{o.name} (line {o.line}): Linux has no {call} on {arch}"
                    )
        for call in o.needs:
            if call not in implemented:
                found.append(
                    f"{o.name} (line {o.line}) is {o.value} but {call} is not implemented"
                )
    return list(dict.fromkeys(found))


def render(options: list[Option], arch: str, release: str) -> str:
    """The config file for `arch`, in the format of Linux's .config."""
    lines = [
        "#",
        "# Automatically generated file; DO NOT EDIT.",
        f"# VeridianOS {release} ({arch}): the Linux features it provides",
        "# Generated by tools/compat/gen_kconfig.py from abi/kconfig.map (ADR 0023)",
        "#",
    ]
    for o in options:
        if arch not in o.arches:
            continue
        lines.append(
            f"# {o.name} is not set" if o.value == "n" else f"{o.name}={o.value}"
        )
    return "\n".join(lines) + "\n"


def release() -> str:
    """The release uname reports (kernel/src/utils/uname.rs)."""
    src = (REPO / "kernel/src/utils/uname.rs").read_text()
    match = re.search(r'pub const RELEASE: &str = "([^"]+)";', src)
    if not match:
        sys.exit("gen_kconfig: no RELEASE in kernel/src/utils/uname.rs")
    return match.group(1)


def load() -> list[Option]:
    try:
        return parse((REPO / "abi/kconfig.map").read_text())
    except ValueError as e:
        sys.exit(f"gen_kconfig: {e}")


def main() -> None:
    args = sys.argv[1:]
    if args == ["--check"]:
        implemented, _ = syscall_coverage.veridian_status()
        linux = {
            a: {name for _, name, ok in syscall_coverage.linux_rows(a) if ok}
            for a in ARCHES
        }
        found = problems(load(), implemented, linux)
        if found:
            sys.exit(
                "gen_kconfig: abi/kconfig.map claims too much:\n  " + "\n  ".join(found)
            )
    elif len(args) == 2 and args[0] == "--print" and args[1] in ARCHES:
        sys.stdout.write(render(load(), args[1], release()))
    elif len(args) == 2 and args[0] in ARCHES:
        rel = release()
        out = Path(args[1]) / "boot" / f"config-{rel}"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(render(load(), args[0], rel))
    else:
        sys.exit("usage: gen_kconfig.py --check | --print ARCH | ARCH ROOT")


if __name__ == "__main__":
    main()
